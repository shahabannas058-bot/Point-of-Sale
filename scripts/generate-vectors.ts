/**
 * Writes the golden vectors in /testdata that the .NET shell tests (apps/shell-dotnet/*.Tests) replay, so the C#
 * ports provably agree with the TypeScript reference. Every expected value is computed here by the TS code.
 *
 *   npm run vectors      (= npx tsx scripts/generate-vectors.ts && prettier --write testdata)
 *
 * Output is deterministic: fixed clocks and seeded byte streams only.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { checksum, migrationsFromFiles } from '../packages/db/src/migrate';
import { buildHelperCases } from './vectors/helpers';
import { buildInvoiceVectors } from './vectors/invoices';
import { buildUuidScenarios } from './vectors/uuids';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const TESTDATA = join(ROOT, 'testdata');
const MIGRATIONS = join(ROOT, 'packages', 'db', 'migrations');
const NOTICE = 'Generated by scripts/generate-vectors.ts (npm run vectors). Do not edit by hand.';

function write(file: string, body: Record<string, unknown>): void {
  const path = join(TESTDATA, file);
  writeFileSync(path, `${JSON.stringify(body, null, 2)}\n`, 'utf8');
  process.stdout.write(`wrote ${path}\n`);
}

function migrationChecksums(): { version: number; name: string; checksum: string }[] {
  const files: Record<string, string> = {};
  for (const name of readdirSync(MIGRATIONS).sort())
    files[`migrations/${name}`] = readFileSync(join(MIGRATIONS, name), 'utf8');
  return migrationsFromFiles(files).map((m) => ({
    version: m.version,
    name: m.name,
    checksum: checksum(m.sql),
  }));
}

write('invoice-vectors.json', { _generated: NOTICE, vectors: buildInvoiceVectors() });
write('helper-vectors.json', { _generated: NOTICE, cases: buildHelperCases() });
write('uuid-vectors.json', { _generated: NOTICE, scenarios: buildUuidScenarios() });
write('migration-checksums.json', { migrations: migrationChecksums() });
